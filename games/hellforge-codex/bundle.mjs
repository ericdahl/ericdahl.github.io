import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const directory = dirname(fileURLToPath(import.meta.url));

export async function makeBundle() {
  const game = await readFile(join(directory, 'game.js'), 'utf8');
  const main = await readFile(join(directory, 'main.js'), 'utf8');
  const exports = [...game.matchAll(/^export (?:const|function) /gm)].length;
  if (exports < 10) throw new Error('Unexpected game module format');
  if (!main.startsWith("import { TILE, SIZE, CLASSES, SLOTS, createGame")) throw new Error('Unexpected main module format');
  const gameBody = game.replace(/^export /gm, '');
  const mainBody = main.replace(/^import \{[^\n]+\} from '\.\/game\.js';\n/, '');
  if (mainBody === main) throw new Error('Could not remove module import');
  return `/* Generated by npm run bundle. Edit game.js and main.js instead. */\n(function () {\n'use strict';\n${gameBody}\n${mainBody}\n})();\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writeFile(join(directory, 'hellforge.js'), await makeBundle());
}
